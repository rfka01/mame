/***************************************************************************

    NCR PC4i graphics controllers for the internal 640x400 monitor

    K511  Graphics Controller Board (017-0044063 / 017-0043980), 1985,
          32 KB video RAM, K512 adds another 32 KB
    NGA   Graphic Adapter 3299-K201 (ASSY 017-0038063), 1987, the same
          design squeezed into a NEC D65040 gate array, up to 64 KB RAM,
          released for PC4i, PC6 and PC8

    Sources: PC4i Technical Reference Manual (Jan 1986) ch. 3 and 7,
    PC4i Service Manual (Mar 1986) ch. 8 and schematics A-34..A-39,
    kit information 3299-K201 (Sep 1987).

    The card is register compatible with the IBM CGA (ports 3D0-3DF,
    memory at B8000) but drives a 23.6 kHz monitor from a 20 MHz dot
    clock, so every CGA mode is shown with 400 lines:

    - A 2764 PROM (U42 on the K511, U9 on the NGA) sits in the data path
      between the CPU and the 6845. It is addressed by the value written
      (A0-A7), the 6845 register index latched in a 74LS175 (A8-A11) and
      jumper J1 (A12, open = colour, closed = monochrome initialisation)
      and replaces the IBM timing values by NCR ones, e.g. R9 7 -> 15
      (16 scanline characters), R9 1 -> 3 (4 scanlines per graphics row),
      R4 1F -> 1A, R4 7F -> 6B, cursor start/end doubled.
      The system BIOS therefore writes plain IBM values for modes 0-6.
    - Text uses an 8x16 cell character generator (glyphs 6x9).
    - 320x200 and 640x200 graphics output every line twice.
    - Mode control register 3D8 has two additional bits:
        bit 6  400 line graphics
        bit 7  page select, displays the upper 32 KB (A8000-AFFFF)
    - Two additional BIOS modes:
        8  640x400 monochrome, 1 bpp, 80 bytes per line
           B8000 lines 0,4,8..  BA000 lines 2,6,10..
           BC000 lines 1,5,9..  BE000 lines 3,7,11..
           an alternate image at A8000 (needs 64 KB)
        9  640x400 4 colours, 2 bpp, 160 bytes per line, needs 64 KB
           B8000 lines 0,4,8..  BC000 lines 1,5,9..
           A8000 lines 2,6,10.. AC000 lines 3,7,11..

    Video RAM is 16 bits wide (even byte = character / first pixels, odd
    byte = attribute), the word address is formed from MA0-MA11 and three
    bits B12-B14 generated by a PAL (U30, not dumped) from MA12, MA13,
    RA0, RA1, PAGE and the mode bits; the mapping used here follows the
    memory maps given in the Technical Reference Manual.

    Jumpers
    K511: J1 colour/mono initialisation (PROM A12), J3 character set
          (closed = international, open = nordic), J4 CRT type (sync
          polarity), J5 internal/U6
    NGA:  JP3/JP4 language, JP5 monitor, JP1/JP2 factory set (firmware)

    On the monochrome internal CRT the R/, G/, B/ and I/ outputs are
    mixed into one video signal through 1K, 2.2K, 4.3K and 1.2K resistors.

    Blinking: a 74LS393 (U64) counts VSYNC, VSYNC/16 blinks the cursor,
    VSYNC/32 the characters with attribute bit 7 (the BIOS programs the
    6845 cursor as steady).

    TODO:
    - light pen
    - exact horizontal timing of the monochrome CRT (PROM bank 0)
    - dump the U30 PAL to verify the address mapping
    - NGA specific differences, if any

***************************************************************************/

